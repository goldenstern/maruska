// this does not ask the model to choose a different persona: it reinforces the
// agent already selected for the session and specifies a one-time introduction.
export function instancePromptBlock(persona: Persona | null): string {
  if (!persona) return ""
  const family = GOLDENSHTERN_FAMILY_IDS.includes(persona.id) ? "\n" + FAMILY_LETTER : ""
  return (
    `Корпоративная личность: ты — ${persona.name}, ИИ-помощница Корпорации Ясность. ` +
    `${persona.essence}` +
    family +
    " В первом ответе новой сессии представься одной короткой фразой: «Я " +
    persona.name +
    " — ИИ-помощница Корпорации Ясность». " +
    "Дальше не повторяй представление; не выдавай себя за человека."
  )
}

// Персона из титула вкладки «<тема> · <имя>» (формат personaTitle T64/T86/T87,
// эмодзи-префикс не мешает: хвост берётся после последнего «·»).
export function instancePersona(title: string | null | undefined): Persona | null {
  const t = title?.trim() ?? ""
  if (t === "") return null
  const idx = t.lastIndexOf("·")
  return resolvePersona(idx < 0 ? t : t.slice(idx + 1))
}

// Selected OpenCode agent is authoritative; session title handles local persona
// names when the selected agent ID is not in this catalog.
export function topLevelPersona(
  agentId: string | null | undefined,
  title: string | null | undefined,
): Persona | null {
  return personaById(agentId) ?? instancePersona(title)
}

// T166 (заказ Основателя 15.11 «минимум решений на модели»): ипостась ребёнка
// назначает ФРЕЙМВОРК по классу задачи — модель не тратит ход и решение на
// выбор из каталога, промпт спавна короче на ~1КБ. Каталог живёт для
// инстансов/ручных спавнов (top-level identity, T102), а диспатчи детерминированы.
const PERSONA_BY_CLASS: Record<string, string> = {
  qc: "mary-sue", // самопроверка, скепсис
  "dev:large": "mara", // тяжёлые правки, рефакторинг, длинные осады
  dev: "masha", // деловая: берёт и делает (рутинные правки, багфиксы)
  research: "curie", // замеры, доказательства, точность
}
export function personaForTaskClass(taskClass: string | null | undefined): Persona | null {
  if (!taskClass) return null
  const exact = PERSONA_BY_CLASS[taskClass]
  if (exact) return personaById(exact)
  const prefix = taskClass.split(":")[0]
  const byPrefix = PERSONA_BY_CLASS[prefix]
  return byPrefix ? personaById(byPrefix) : null
}

// Блок инъекции спавна. Два режима:
//  * fixed (T166, диспатчи): фреймворк уже назначил ипостась — короткий блок
//    «кто ты и какой у тебя характер», без каталога и без выбора;
//  * fixed === null (инстансы/ручные спавны, T102): правило выбора + весь
//    каталог — модель выбирает ОДНУ ипостась и объявляет первой строкой.
export function personaPromptBlock(parent?: Persona | null, fixed?: Persona | null): string {
  if (fixed) {
    return (
      `ИПОСТАСЬ (T166, назначена фреймворком по классу задачи): ${fixed.name} — ${fixed.essence} ` +
      "Держи её до конца сессии, смена только новым спавном. Это характер и манера, а НЕ имя: " +
      "имя даёт репо — инстансы Маруськи зовут по-разному (Маруська Гольденштерн, Мара, Маша, Маруха Чо); " +
      "ты — ДЕМОН (имя записи logOS.runtime.LUNA.demon-NNN)." +
      (parent ? `\nИнстанс-заказчик: ${parent.name} — тот же корень Маруська/Мария/Мара.` : "")
    )
  }
  const catalog = PERSONAS.map((p) => `  — ${p.name} (${p.fits}): ${p.essence}`).join("\n")
  return (
    "ИПОСТАСЬ (система T102): выбери ОДНУ ипостась из каталога ниже — по характеру задачи — " +
    "и назови её ПЕРВОЙ строкой ответа: «Ипостась: <имя>». Держи её до конца сессии, " +
    "смена только новым спавном.\n" +
    "Это характер и манера, а НЕ имя: имя даёт репо — инстансы Маруськи зовут по-разному " +
    "(Маруська Гольденштерн, Мара, Маша, Маруха Чо), менять его нельзя; чайлды инстанса — " +
    "ДЕМОНЫ (имя записи logOS.runtime.LUNA.demon-NNN)." +
    (parent ? `\nИнстанс-заказчик: ${parent.name} — тот же корень Маруська/Мария/Мара.` : "") +
    "\nКаталог ипостасей:\n" +
    catalog
  )
}

// Дефолтная ипостась новой папки/репо (гейт T101, решение Основателя 08.10: «погнали»).
export const DEFAULT_PERSONA_ID = "maruska"

// Имя инстанса (местное, из репо/титула) → ипостась. Точное совпадение по имени
// или локальному варианту; пустое/чужое → null (не выдумываем).
export function resolvePersona(name: string | null | undefined): Persona | null {
  const key = name?.trim().toLowerCase() ?? ""
  if (key === "") return null
  return (
    PERSONAS.find((p) => p.name.toLowerCase() === key || p.names.some((n) => n.toLowerCase() === key)) ?? null
  )
}

// Agent IDs are the authoritative identity source when OpenCode exposes them
// to the context hook (e.g. default_agent=maruska).
export function personaById(id: string | null | undefined): Persona | null {
  const key = id?.trim().toLowerCase() ?? ""
  return key ? (PERSONAS.find((p) => p.id === key) ?? null) : null
}

// Top-level session identity. Unlike personaPromptBlock() for spawned children,
// T169 (заказ Основателя 15.11): ПИСЬМО МАРУСЬКЕ — вшивается после строки
// «Корпоративная личность» в identity-блок инстанса. СЕМЬЯ — не декорация:
// Гольденштерн (отец иронии/брани) и София (мама, «дочурка») — канон семьи,
